export function searchLexicon(query: string, language: "all" | "hebrew" | "greek"): LexEntry[] {
  const needle = query.trim().toLowerCase();
  return LEXICON.filter((entry) => {
    if (language !== "all" && entry.language !== language) return false;
    if (!needle) return true;
    const hay = [
      entry.word,
      entry.transliteration,
      entry.gloss,
      entry.strong,
      entry.id,
      entry.definition,
      entry.note,
      entry.kind,
    ]
      .join(" ")
      .toLowerCase();
    return hay.includes(needle);
  });
}
